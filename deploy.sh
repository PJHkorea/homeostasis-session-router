#!/usr/bin/env bash
# =========================================================================
# [Sovereign Buffer Cache - Ingress & Session Router Integration Deploy Engine]
# =========================================================================
set -euo pipefail

# 전역 가드레일 제어 전 장착 (스크립트 오류 발생 시 즉각 안전 격리)
TRACE_ID="[HOMEOSTASIS_DEPLOY_$(date +%s)]"
echo "${TRACE_ID} ⚡ 차세대 항상성 면역 인프라 생태계 네이티브 전개 시동..."

# -------------------------------------------------------------------------
# 1. 🎛️ 호스트 OS 로우레벨 드라이버 및 네트워크 카드(NIC) 인프라 스캔
# -------------------------------------------------------------------------
# 가상 루프백(lo) 인터페이스를 배제하고, 실제 와이어 스피드가 흐르는 물리 NIC 자동 추적
TARGET_IFACE=$(ip -o link show | awk -F': ' '$2 != "lo" && $3 ~ /UP/ {print $2; exit}')

if [ -z "${TARGET_IFACE}" ]; then
    echo "[-] 치명적 결함: 활성화된 물리 네트워크 인터페이스(NIC)를 발견하지 못했습니다." >&2
    exit 1
fi
echo "[+] 성공: 타겟 하드웨어 와이어 스피드 인터페이스 래칭 완료 -> ${TARGET_IFACE}"

# -------------------------------------------------------------------------
# 2. 💾 [Memory Hard-locking 준비] 호스트 OS 커널 메모리 가드 전면 해제
# -------------------------------------------------------------------------
# 정적 래티스 맵(1,000만 슬롯 = 640MB)이 리눅스 커널 공간(Kernel Space)에 선점 적재될 때,
# RLIMIT_MEMLOCK 상한 제한으로 인해 적재가 정적 거부당하는 현상을 물리적으로 완전 분쇄합니다.
echo "[*] 최적화: 호스트 리눅스 커널 정적 메모리 고정 상한선(MEMLOCK) 무한대 확장..."
ulimit -l unlimited

# -------------------------------------------------------------------------
# 3. 🚨 [Fail-Safe 가드레일]: 비상 크래시 발생 시 원터치 강제 원복 트랩 매핑
# -------------------------------------------------------------------------
# 컴파일 및 시뮬레이션 구동 중 예기치 못한 인터럽트(Ctrl+C)나 예외 발생 시, 
# 네트워크 카드가 다운된 채 멈추지 않도록 Native XDP 필터를 NIC 레일에서 강제 인쇄 청소합니다.
rollback_emergency_barrier() {
    echo -e "\n[⚠️ EMERGENCY ROLLBACK] 전개 도중 시스템 예외 충격파 감지! 드라이버 원복 집행..."
    # 최전방 인그레스 필터 제거 명령 비동기 투하 (인프라 다운 상쇄)
    ip link set dev "${TARGET_IFACE}" xdp off 2>/dev/null || true
    echo "[+] 완료: 최하단 NIC 드라이버 레이어를 청정 제로 베이스 상태로 안전 원복했습니다."
}
trap rollback_emergency_barrier ERR INT TERM

# -------------------------------------------------------------------------
# 4. 🛠️ 멀티 스테이지 컴파일 오케스트레이션 구동
# -------------------------------------------------------------------------
echo -e "\n[Step 1] Docker 멀티 스테이지 엔진을 통한 이종 언어 가속 커널 일괄 정류 합성 시작..."
# 호스트 환경 파편화 오염 없이 독립 컨테이너 내부에서 정적 기계어 컴파일을 종결합니다.
docker build -t homeostasis/session-router:latest -f Dockerfile .

# -------------------------------------------------------------------------
# 5. 🌊 Native XDP 관문 네트워크 카드 최하단 드라이버 레일 하이재킹 적재
# -------------------------------------------------------------------------
echo -e "\n[Step 2] 최전방 무분기 실리콘 비트 MUX 게이트 드라이버 하드웨어 적재 시작..."

# 임시 실행 컨테이너를 가동하여 내부에서 빌드 완료된 `bitwise_session_mux.o` 바이트코드를 
# 호스트의 bpftool 및 iproute2 서브시스템 레이어로 추출 인터록합니다.
docker run --rm --entrypoint cat homeostasis/session-router:latest /app/kernel/bitwise_session_mux.o > ./bitwise_session_mux.o

# Native XDP 모드(네트워크 인터페이스 드라이버 회로 최하단 경로)로 직접 주입 가동
# JMP 조건 분기문이 영구 거세된 1-Cycle 정수 고정소수점 왜도 연산 배리어가 호스트 NIC를 하이재킹합니다.
ip link set dev "${TARGET_IFACE}" xdp object ./bitwise_session_mux.o section xdp

echo "[+] 성공: 최하단 드라이버 링버퍼 레일 주입 완료. 14.88 Mpps 폭격 면역 가드 각성."

# -------------------------------------------------------------------------
# 6. 🧠 마스터 컨트롤 플레인 및 4차원 텐서 비침습 관제 론치
# -------------------------------------------------------------------------
echo -e "\n[Step 3] Rust 마스터 오케스트레이터 및 4x4 대수학 섀도우 관제탑 허브 최종 실전 전개..."

# --privileged 플래그와 호스트 네트워크(`--net=host`)를 바인딩하여 
# Rust 프록시가 mmap 주소선으로 커널의 HBM 영역에 직접 락프리 원자적 비트 주입을 집행하도록 전개합니다.
# 동시에 NVML 하드웨어 레지스터 텔레메트리 연동을 위해 GPU 가속 자원을 완전 기부 공유합니다.
docker run -d \
    --name homeostasis_session_router_runtime \
    --privileged \
    --net=host \
    --gpus all \
    -v /sys/fs/bpf:/sys/fs/bpf \
    -v /proc:/host/proc:ro \
    homeostasis/session-router:latest

# -------------------------------------------------------------------------
# 7. 🎯 무결성 항상성 전개 최종 성적표 리포트
# -------------------------------------------------------------------------
echo -e "\n========================================================================="
echo "🔥 [결론] 차세대 크로스 도메인 항상성 세션 라우터 인프라 전개 무결성 봉인 완료."
echo " - 가동 인터페이스 : ${TARGET_IFACE} (Native XDP 와이어 스피드 가속 트랙)"
echo " - 공간 복잡도 마진 : 640MB 커널 고정 선점 동결 (공간 복잡도 O(1) 달성)"
echo " - 하드웨어 가속기 : NVIDIA GPU / NVML 비침습 전력 파형 이중 확증 상태 온"
echo "========================================================================="

# 임시 빌드 찌꺼기 자원 청정화 리셋
rm -f ./bitwise_session_mux.o
